package mips;

/**
 * Rutinas de soporte que acompañan a todo programa generado (en ensamblador MIPS).
 * Son rutinas hoja: solo usan $t0–$t9, $a0–$a3 y $v0–$v1 (nunca los $s), de modo que no alteran los
 * temporales del TAC que viven en registros guardados.
 */
final class MipsRuntime {
    private MipsRuntime() {}

    /** Datos que necesita el runtime (se agregan a la sección .data). */
    static String data(int globalBytes) {
        StringBuilder sb = new StringBuilder();
        sb.append("# --- datos del runtime ---\n");
        sb.append("G_data:     .space ").append(Math.max(4, globalBytes)).append("      # variables globales (gp)\n");
        sb.append("__hptr:     .word __hstack            # tope de la pila de manejadores de excepciones\n");
        sb.append("__exc:      .word 0                   # ultima excepcion lanzada\n");
        sb.append("__hstack:   .space 768                # 64 manejadores x (direccion, sp, fp)\n");
        sb.append("__s_null:   .asciiz \"null\"\n");
        sb.append("__s_true:   .asciiz \"true\"\n");
        sb.append("__s_false:  .asciiz \"false\"\n");
        sb.append("__m_oob:    .asciiz \"indice fuera de rango\"\n");
        sb.append("__m_div0:   .asciiz \"division por cero\"\n");
        sb.append("__m_nullref: .asciiz \"referencia nula\"\n");
        sb.append("__m_unc:    .asciiz \"Excepcion no capturada: \"\n");
        return sb.toString();
    }

    /** Código de las rutinas (sección .text, después de las funciones del programa). */
    static String text() {
        return String.join("\n",
            "# ======================================================================",
            "# Runtime",
            "# ======================================================================",
            "",
            "# imprime el entero de $a0 y un salto de linea",
            "__print_int:",
            "    li $v0, 1",
            "    syscall",
            "    li $a0, 10",
            "    li $v0, 11",
            "    syscall",
            "    jr $ra",
            "",
            "# imprime la cadena de $a0 (null si es 0) y un salto de linea",
            "__print_str:",
            "    bnez $a0, __ps_ok",
            "    la $a0, __s_null",
            "__ps_ok:",
            "    li $v0, 4",
            "    syscall",
            "    li $a0, 10",
            "    li $v0, 11",
            "    syscall",
            "    jr $ra",
            "",
            "# imprime true/false segun $a0",
            "__print_bool:",
            "    beqz $a0, __pb_false",
            "    la $a0, __s_true",
            "    j __print_str",
            "__pb_false:",
            "    la $a0, __s_false",
            "    j __print_str",
            "",
            "# concatena las cadenas $a0 y $a1; devuelve la nueva cadena en $v0",
            "__concat:",
            "    bnez $a0, __cc_a",
            "    la $a0, __s_null",
            "__cc_a:",
            "    bnez $a1, __cc_b",
            "    la $a1, __s_null",
            "__cc_b:",
            "    move $t5, $a0",
            "    move $t6, $a1",
            "    move $t0, $a0",
            "    li $t2, 0",
            "__cc_l1:",
            "    lb $t3, 0($t0)",
            "    beqz $t3, __cc_l2",
            "    addiu $t0, $t0, 1",
            "    addiu $t2, $t2, 1",
            "    j __cc_l1",
            "__cc_l2:",
            "    move $t1, $a1",
            "    li $t4, 0",
            "__cc_l3:",
            "    lb $t3, 0($t1)",
            "    beqz $t3, __cc_l4",
            "    addiu $t1, $t1, 1",
            "    addiu $t4, $t4, 1",
            "    j __cc_l3",
            "__cc_l4:",
            "    addu $a0, $t2, $t4",
            "    addiu $a0, $a0, 1",
            "    li $v0, 9",
            "    syscall",
            "    move $t7, $v0",
            "    move $t0, $v0",
            "    move $t1, $t5",
            "__cc_c1:",
            "    lb $t3, 0($t1)",
            "    beqz $t3, __cc_c2",
            "    sb $t3, 0($t0)",
            "    addiu $t0, $t0, 1",
            "    addiu $t1, $t1, 1",
            "    j __cc_c1",
            "__cc_c2:",
            "    move $t1, $t6",
            "__cc_c3:",
            "    lb $t3, 0($t1)",
            "    sb $t3, 0($t0)",
            "    beqz $t3, __cc_c4",
            "    addiu $t0, $t0, 1",
            "    addiu $t1, $t1, 1",
            "    j __cc_c3",
            "__cc_c4:",
            "    move $v0, $t7",
            "    jr $ra",
            "",
            "# compara las cadenas $a0 y $a1 por contenido; $v0 = 1 si son iguales",
            "__streq:",
            "    beq $a0, $a1, __se_true",
            "    beqz $a0, __se_false",
            "    beqz $a1, __se_false",
            "__se_l:",
            "    lb $t0, 0($a0)",
            "    lb $t1, 0($a1)",
            "    bne $t0, $t1, __se_false",
            "    beqz $t0, __se_true",
            "    addiu $a0, $a0, 1",
            "    addiu $a1, $a1, 1",
            "    j __se_l",
            "__se_true:",
            "    li $v0, 1",
            "    jr $ra",
            "__se_false:",
            "    li $v0, 0",
            "    jr $ra",
            "",
            "# excepciones: cada rutina carga su mensaje y salta a __throw",
            "__oob:",
            "    la $a0, __m_oob",
            "    j __throw",
            "__div0:",
            "    la $a0, __m_div0",
            "    j __throw",
            "__nullref:",
            "    la $a0, __m_nullref",
            "    j __throw",
            "",
            "# lanza la excepcion cuyo mensaje esta en $a0: restaura $sp/$fp del manejador activo y salta a el",
            "__throw:",
            "    lw $t9, __hptr",
            "    la $t8, __hstack",
            "    beq $t9, $t8, __unc",
            "    addiu $t9, $t9, -12",
            "    sw $t9, __hptr",
            "    sw $a0, __exc",
            "    lw $t8, 0($t9)",
            "    lw $sp, 4($t9)",
            "    lw $fp, 8($t9)",
            "    jr $t8",
            "__unc:",
            "    move $t0, $a0",
            "    la $a0, __m_unc",
            "    li $v0, 4",
            "    syscall",
            "    move $a0, $t0",
            "    li $v0, 4",
            "    syscall",
            "    li $a0, 10",
            "    li $v0, 11",
            "    syscall",
            "    li $v0, 10",
            "    syscall",
            "") + "\n";
    }
}
